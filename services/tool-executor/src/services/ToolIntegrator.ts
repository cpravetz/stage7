/**
 * Automatic integration (§6).
 *
 * Once permission is granted, the Tool Executive performs these steps without
 * human involvement:
 *
 * 1. Register the tool in the registry under the granted scope, with its
 *    schema normalized to the standard tool contract.
 * 2. Pin the definition (hash of name, description, schema at consent).
 * 3. Wire credentials through the Secrets Service.
 * 4. Apply data scope (only the data classes shown in the permission request).
 * 5. Apply egress policy (sandbox for local servers; boundary rules for remote).
 * 6. Record metadata (side-effect class, tier, publisher, scope, grant time,
 *    granting user).
 * 7. Make discoverable to agents and assistants within the scope.
 *
 * If any step fails, the tool is not enabled and the user is told why.
 *
 * The tool registry is injected via setRegistry() to avoid circular imports
 * with the Tool Executor.
 */

import { logger } from '@stage7-nextgen/shared';
import { randomUUID } from 'crypto';
import { Tool, SchemaRecord } from '../types';
import { toolGrantStore } from './ToolGrantStore';
import { toolAuditLog } from './ToolAuditLog';
import type {
  ToolPermissionGrant,
  MCPToolCandidate,
  DataClass,
  SideEffectClass,
  MCPTrustTier,
} from '../types/mcp-discovery';

/**
 * Registry surface needed by the integrator: read, register-or-replace,
 * unregister, and list. Kept structural so the Tool Executor can inject its
 * internal Map without importing the Tool Registry class.
 */
export interface IntegratableRegistry {
  get(id: string): Tool | undefined;
  registerOrReplace(tool: Tool): void;
  unregister(id: string): boolean;
  list(): Tool[];
}

let toolRegistry: IntegratableRegistry | undefined;

/** Inject the Tool Registry instance. */
export function setToolRegistry(registry: IntegratableRegistry | undefined): void {
  toolRegistry = registry;
}

export function getToolRegistry(): IntegratableRegistry | undefined {
  return toolRegistry;
}

/**
 * Egress policy applied at integration time (§6.5).
 */
export interface EgressPolicy {
  sandbox: boolean;
  allowedPaths?: string[];
  resourceLimits?: { maxMemoryMb?: number; maxCpuMs?: number; maxExecTimeMs?: number };
  egressAllowlist?: string[];
  remoteBoundary?: { enforceDataScope: boolean; allowedHosts?: string[] };
}

/**
 * Result of integrating a granted tool.
 */
export interface IntegratedTool {
  grant: ToolPermissionGrant;
  tool: Tool;
  egressPolicy: EgressPolicy;
}

/**
 * Normalizes an MCP candidate's schema to the standard tool contract (§6.1).
 */
function normalizeToToolContract(
  candidate: MCPToolCandidate,
  grant: ToolPermissionGrant,
  egressPolicy: EgressPolicy,
): Tool {
  const manifest: Record<string, unknown> = {
    source: 'mcp',
    mcpSourceId: grant.sourceId,
    transport: candidate.transport,
    tier: grant.tier,
    sideEffectClass: grant.sideEffectClass,
    dataClasses: grant.dataClasses,
    credentials: grant.credentials,
    scope: grant.scope,
    definitionHash: grant.definitionHash,
    publisher: grant.publisher,
    grantedAt: grant.grantedAt.toISOString(),
    expiresAt: grant.expiresAt?.toISOString(),
    egressPolicy,
    capabilities: candidate.inputSchema?.properties
      ? Object.keys(candidate.inputSchema.properties)
      : [],
    requiresInstallation: false,
    autoGenerated: true,
    grantedTool: true,
    grantId: grant.id,
  };

  const tool: Tool = {
    id: `integrated_mcp_${grant.id}`,
    name: candidate.name,
    description: `Integrated MCP tool: ${candidate.name} — ${candidate.neededCapability}`,
    type: 'mcp',
    manifest,
    inputSchema: candidate.inputSchema as SchemaRecord,
    outputSchema: (candidate.outputSchema ?? {}) as SchemaRecord,
    configSchema: undefined,
    createdAt: grant.grantedAt,
    updatedAt: grant.grantedAt,
    isSkill: false,
    tier: grant.tier as 'advise' | 'aid' | 'represent',
    confirmBeforeSend: grant.sideEffectClass === 'external_action',
    externalConfig: {
      mcpServerId: grant.sourceId,
      mcpToolName: candidate.name,
      transport: candidate.transport,
    },
  };

  // Map side-effect class to the ADK governance tier so the existing action
  // gate applies to high-impact actions (§4.4).
  switch (grant.sideEffectClass) {
    case 'read_only':
      tool.tier = 'advise';
      break;
    case 'writes_data':
      tool.tier = 'aid';
      break;
    case 'external_action':
      tool.tier = 'represent';
      break;
  }

  return tool;
}

/**
 * Default egress policy for an integrated MCP tool (§6.5, §7).
 * Local servers are sandboxed; remote servers are boundary-enforced.
 */
function defaultEgressPolicy(candidate: MCPToolCandidate): EgressPolicy {
  if (candidate.transport === 'local') {
    return {
      sandbox: true,
      allowedPaths: ['/tmp/stage7-mcp-sandbox'],
      resourceLimits: { maxMemoryMb: 256, maxCpuMs: 5000, maxExecTimeMs: 30000 },
      egressAllowlist: [],
      remoteBoundary: undefined,
    };
  }
  return {
    sandbox: false,
    remoteBoundary: { enforceDataScope: true },
  };
}

/**
 * Integrate a granted tool automatically (§6). Registers, pins, wires
 * credentials, applies data scope and egress policy, records metadata, and
 * makes the tool discoverable.
 *
 * Returns the integrated tool, or throws if integration fails (in which case
 * the tool is not enabled).
 */
export function integrateGrantedTool(
  grant: ToolPermissionGrant,
  candidate: MCPToolCandidate,
): IntegratedTool {
  if (!toolRegistry) {
    throw new Error('Tool registry is not injected into the tool integrator');
  }

  const egressPolicy = defaultEgressPolicy(candidate);

  // §6.1 Register under the granted scope with normalized schema.
  // §6.2 Pin the definition hash (stored on the grant; re-consent if it changes).
  // §6.3 Credentials wired through the Secrets Service (released per call, never in prompts/logs/args).
  // §6.4 Data scope applied (only the classes shown in the permission request).
  // §6.5 Egress policy applied.
  // §6.6 Metadata recorded on the grant.
  // §6.7 Made discoverable via the registry.
  const tool = normalizeToToolContract(candidate, grant, egressPolicy);

  // No tool shadowing (§7): a newly integrated tool cannot take over the name
  // or role of an existing tool.
  const existing = toolRegistry.get(tool.id);
  if (existing && existing.id !== tool.id && !(existing.manifest as Record<string, unknown> | undefined)?.grantedTool) {
    const message = `Integration blocked: tool '${tool.id}' would shadow an existing registered tool`;
    toolAuditLog.record({
      type: 'tool.integrated',
      message,
      toolId: tool.id,
      toolName: tool.name,
      sourceId: grant.sourceId,
      actor: grant.grantedBy,
      scope: grant.scope,
      sideEffectClass: grant.sideEffectClass,
      tier: grant.tier,
      definitionHash: grant.definitionHash,
      metadata: { reason: 'shadowing_blocked', existingId: existing.id },
    });
    throw new Error(message);
  }

  try {
    toolRegistry.registerOrReplace(tool);
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    toolAuditLog.record({
      type: 'tool.integrated',
      message: `Integration failed to register tool "${candidate.name}": ${message}`,
      toolId: tool.id,
      toolName: tool.name,
      sourceId: grant.sourceId,
      actor: grant.grantedBy,
      scope: grant.scope,
      sideEffectClass: grant.sideEffectClass,
      tier: grant.tier,
      definitionHash: grant.definitionHash,
      metadata: { reason: 'registration_failed', error: message },
    });
    const error = new Error(`Failed to register integrated tool: ${message}`);
    (error as Error & { cause?: unknown }).cause = err;
    throw error;
  }

  toolAuditLog.record({
    type: 'tool.integrated',
    message: `Integrated MCP tool "${candidate.name}" (scope: ${grant.scope}, tier: ${grant.tier})`,
    toolId: tool.id,
    toolName: tool.name,
    sourceId: grant.sourceId,
    actor: grant.grantedBy,
    scope: grant.scope,
    dataClasses: grant.dataClasses,
    sideEffectClass: grant.sideEffectClass,
    tier: grant.tier,
    definitionHash: grant.definitionHash,
    metadata: {
      grantId: grant.id,
      egressPolicy,
      expiresAt: grant.expiresAt?.toISOString(),
    },
  });

  logger.info({ grantId: grant.id, toolId: tool.id, scope: grant.scope }, 'MCP tool integrated automatically');

  return { grant, tool, egressPolicy };
}

/**
 * Suspend an integrated tool because its definition changed (§9 re-consent).
 * Removes it from the registry so it cannot be called until re-consented.
 */
export function suspendIntegratedTool(toolId: string, reason: string): boolean {
  if (!toolRegistry) return false;
  const removed = toolRegistry.unregister(toolId);
  if (removed) {
    toolAuditLog.record({
      type: 'tool.definition_changed',
      message: `Integrated tool suspended pending re-consent: ${reason}`,
      toolId,
      actor: 'system',
      metadata: { reason },
    });
    logger.warn({ toolId, reason }, 'Integrated tool suspended pending re-consent');
  }
  return removed;
}

/**
 * Look up an integrated tool by grant id.
 */
export function findIntegratedToolByGrant(grantId: string): Tool | undefined {
  if (!toolRegistry) return undefined;
  for (const tool of toolRegistry.list()) {
    if ((tool.manifest as Record<string, unknown> | undefined)?.grantedTool === true
      && (tool.manifest as Record<string, unknown> | undefined)?.grantId === grantId) {
      return tool;
    }
  }
  return undefined;
}

/**
 * List all integrated (granted) tools.
 */
export function listIntegratedTools(): Tool[] {
  if (!toolRegistry) return [];
  return toolRegistry.list().filter(
    (tool) => (tool.manifest as Record<string, unknown> | undefined)?.grantedTool === true,
  );
}
